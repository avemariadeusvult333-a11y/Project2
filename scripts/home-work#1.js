/*
    ========================================
    6. ФУНКЦИИ
    ========================================

    Функция — это блок кода, который можно запускать много раз.

    Она помогает:
    - не повторять один и тот же код
    - делать программу более понятной
    - разделять код на логические части

    Функция выполняется только тогда, когда мы её вызываем.

    Общий вид функции:

    function имяФункции(параметры) {
    код
    }

    Чтобы запустить функцию, нужно написать:

    имяФункции()
*/


/*
    ========================================
    1. ОБЫЧНАЯ ФУНКЦИЯ
    ========================================

    Это самый простой и базовый тип функции.
*/

function sayHello() {
  console.log("Привет")
}

/*
    Запуск функции
*/

sayHello()


/*
    Функцию можно вызывать сколько угодно раз
*/

sayHello()
sayHello()



/*
    ========================================
    2. ФУНКЦИЯ С ПАРАМЕТРАМИ
    ========================================

    Параметры — это данные, которые передаются в функцию.

    Они позволяют функции работать с разными значениями.
*/

function greet(name) {
  console.log("Привет " + name)
}

/*
    При вызове функции передаем аргумент
*/

greet("Антон")
greet("Катя")
greet("Саша")



/*
    Результат:

    Привет Антон
    Привет Катя
    Привет Саша
*/



