/*
    ========================================
    4. ФУНКЦИЯ С RETURN
    ========================================

    Иногда функция должна вернуть результат.

    Для этого используется слово return.

    return завершает выполнение функции
    и возвращает значение наружу.
*/

function sum(a, b) {
  return a + b
}

/*
    Сохраняем результат в переменную
*/

const result = sum(5, 3)
console.log(result)


